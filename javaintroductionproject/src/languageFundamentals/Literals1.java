package languageFundamentals;

/*
 * 2.Write a Java program to declare and display variables using the following literals:
Integer literal
Floating-point literal
Character literal
String literal
Boolean literal

*/
public class Literals1 {

	public static void main(String[] args) {
		// Integer literal
        int number = 100;

        // Floating-point literal
        double price = 99.99;

        // Character literal
        char grade = 'A';

        // String literal
        String name = "Lakshmi";

        // Boolean literal
        boolean isStudent = true;
        
        
        
        System.out.println("Integer literal: " + number);
        System.out.println("Floating-point literal: " + price);
        System.out.println("Character literal: " + grade);
        System.out.println("String literal: " + name);
        System.out.println("Boolean literal: " + isStudent);
		     
	}

}

